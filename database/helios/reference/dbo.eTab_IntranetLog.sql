-- Referenční struktura; existující tabulku založenou v Heliosu nemění.
CREATE TABLE dbo.eTab_IntranetLog
(
    ID INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_eTab_IntranetLog PRIMARY KEY,
    IDApp INT NOT NULL,
    IDAkce INT NOT NULL,
    DatAkce DATETIME NOT NULL DEFAULT (GETDATE()),
    Vysledek INT NOT NULL CHECK (Vysledek IN (1,2,3)),
    IDOperace NVARCHAR(36) NOT NULL,
    IDZarizeni INT NULL,
    IDUzivatel INT NULL,
    IDDoklad INT NULL,
    IDPolozkaDokladu INT NULL,
    IDVyrCP INT NULL,
    SSCC NVARCHAR(100) NULL,
    IDInventura INT NULL,
    IDPolozkaInventury INT NULL,
    IDPrikaz INT NULL,
    IDVyrCisPrikaz INT NULL,
    Popis NVARCHAR(1000) NULL,
    Detail NVARCHAR(MAX) NULL,
    Autor NVARCHAR(128) NOT NULL,
    DatPorizeni DATETIME NOT NULL,
    Zmenil NVARCHAR(128) NULL,
    DatZmeny DATETIME NULL,
    BlokovaniEditoru SMALLINT NULL,
    DatPorizeni_D AS (DATEPART(day, DatPorizeni)),
    DatPorizeni_M AS (DATEPART(month, DatPorizeni)),
    DatPorizeni_Y AS (DATEPART(year, DatPorizeni)),
    DatPorizeni_Q AS (DATEPART(quarter, DatPorizeni)),
    DatPorizeni_W AS (DATEPART(week, DatPorizeni)),
    DatPorizeni_X AS (CONVERT(DATETIME, CONVERT(INT, CONVERT(FLOAT, DatPorizeni)))),
    DatZmeny_D AS (DATEPART(day, DatZmeny)),
    DatZmeny_M AS (DATEPART(month, DatZmeny)),
    DatZmeny_Y AS (DATEPART(year, DatZmeny)),
    DatZmeny_Q AS (DATEPART(quarter, DatZmeny)),
    DatZmeny_W AS (DATEPART(week, DatZmeny)),
    DatZmeny_X AS (CONVERT(DATETIME, CONVERT(INT, CONVERT(FLOAT, DatZmeny))))
);
GO
